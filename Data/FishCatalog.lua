function FishCatalog:NormalizeName(name)
    if not name or name == "" then
        return nil
    end
    return tostring(name):lower():gsub("%s+", " "):gsub("^%s+", ""):gsub("%s+$", "")
end

function FishCatalog:Get(itemID, itemName)
    if itemID and self.byID[itemID] then
        return self.byID[itemID]
    end

    local normalizedName = self:NormalizeName(itemName)
    local id = normalizedName and self.byName[normalizedName]
    return id and self.byID[id] or nil
end

function FishCatalog:IsFish(itemID, itemName)
    return self:Get(itemID, itemName) ~= nil
end

function FishCatalog:GetExpansion(itemID, itemName)
    local entry = self:Get(itemID, itemName)
    return entry and entry.expansion or nil
end

