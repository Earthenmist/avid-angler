-- Separate buff families so a ward never suppresses a missing lure.
local buffGroups = { lure = {}, ward = {} }
local buffNameGroups = { lure = {}, ward = {} }
for _, entry in pairs(LureCatalog.byID) do
    local key = entry.pickerKey or "lure"
    for _, spellID in ipairs(entry.buffSpellIDs or {}) do
        buffGroups[key][spellID] = true
    end
    for _, name in ipairs(entry.buffNames or {}) do
        buffNameGroups[key][name:lower()] = true
    end
end

function LureCatalog:GetPickerKey(itemID)
    local entry = self:Get(itemID)
    return entry and (entry.pickerKey or "lure") or nil
end

function LureCatalog:IsPickerBuff(key, spellID, name)
    if spellID then
        return buffGroups[key] and buffGroups[key][spellID] == true or false
    end
    -- Name fallback is only for clients that omit the aura spell ID.
    return buffNameGroups[key] and buffNameGroups[key][tostring(name or ""):lower()] == true or false
end

function LureCatalog:Get(itemID)
    return self.byID[tonumber(itemID or 0)]
end

function LureCatalog:IsLure(itemID)
    return self:Get(itemID) ~= nil
end

function LureCatalog:GetBuffSpellIDs(itemID)
    local entry = self:Get(itemID)
    return entry and entry.buffSpellIDs or nil
end

function LureCatalog:IsPoleEnhancement(itemID)
    local entry = self:Get(itemID)
    return entry and entry.poleEnhancement or false
end

function LureCatalog:IsKnownBuffSpellID(spellID)
    return self.allBuffSpellIDs[tonumber(spellID or 0)] == true
end

function LureCatalog:IsKnownBuffName(name)
    return self.allBuffNames[tostring(name or ""):lower()] == true
end

AvidAngler.Data.LureCatalog = LureCatalog
