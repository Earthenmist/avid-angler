function PoolCatalog:NormalizeName(name)
    if not name or name == "" then
        return nil
    end
    return tostring(name):lower():gsub("%s+", " "):gsub("^%s+", ""):gsub("%s+$", "")
end

function PoolCatalog:Get(objectID, poolName)
    if objectID and self.byObjectID[objectID] then
        return self.byObjectID[objectID]
    end

    local normalizedName = self:NormalizeName(poolName)
    local value = normalizedName and self.byName[normalizedName]
    if type(value) == "number" then
        return self.byObjectID[value]
    end
    return value
end

function PoolCatalog:IsPool(objectID, poolName)
    return self:Get(objectID, poolName) ~= nil
end

function PoolCatalog:GetExpansion(objectID, poolName)
    local entry = self:Get(objectID, poolName)
    return entry and entry.expansion or nil
end

