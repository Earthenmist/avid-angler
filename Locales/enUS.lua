AvidAngler.L = AvidAngler.L or {}
AvidAngler.Locales = AvidAngler.Locales or {}
local L = AvidAngler.L

local DEFAULT_LOCALE = "enUS"

local function CopyInto(target, source)
    if not source then
        return
    end
    for key, value in pairs(source) do
        target[key] = value
    end
end

function AvidAngler:RegisterLocale(locale, label, strings)
    if type(locale) ~= "string" or type(strings) ~= "table" then
        return
    end
    self.Locales[locale] = strings
    self:RefreshLocale()
end

function AvidAngler:GetActiveLocale()
    return self.activeLocale or DEFAULT_LOCALE
end

function AvidAngler:RefreshLocale()
    local requested = (GetLocale and GetLocale()) or DEFAULT_LOCALE
    local activeLocale = self.Locales[requested] and requested or DEFAULT_LOCALE
    local base = self.Locales[DEFAULT_LOCALE]
    local active = self.Locales[activeLocale]

    if not base then
        return
    end

    for key in pairs(self.L) do
        self.L[key] = nil
    end
    CopyInto(self.L, base)
    if active ~= base then
        CopyInto(self.L, active)
    end
    self.activeLocale = activeLocale
end

